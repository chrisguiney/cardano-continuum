package contract

import (
	"bytes"
	"fmt"
	"go/format"
	"io/fs"
	"slices"
	"strings"
)

// Source is one Aiken file of the project.
type Source struct {
	// Path is the file relative to the Aiken project: "validators/vesting.ak".
	Path string `json:"path"`
	// Text is the file's contents.
	Text string `json:"text"`
}

// sourceDirs are the project directories whose .ak files the snapshot
// holds; the compiler's build/ output and its package cache are not source.
var sourceDirs = []string{"lib", "validators"}

// ReadSources reads every .ak file under the project's lib and validators
// directories, keyed by path relative to the project root.
func ReadSources(root fs.FS) (map[string]string, error) {
	out := map[string]string{}
	for _, dir := range sourceDirs {
		err := fs.WalkDir(root, dir, func(p string, d fs.DirEntry, err error) error {
			if err != nil || d.IsDir() || !strings.HasSuffix(p, ".ak") {
				return err
			}

			b, err := fs.ReadFile(root, p)
			if err != nil {
				return err
			}
			out[p] = string(b)
			return nil
		})
		if err != nil {
			return nil, fmt.Errorf("contract: read sources: %w", err)
		}
	}
	return out, nil
}

// RenderSources writes the Go source of sources_gen.go for files.
func RenderSources(files map[string]string) ([]byte, error) {
	paths := make([]string, 0, len(files))
	for p := range files {
		paths = append(paths, p)
	}
	slices.Sort(paths)

	var b bytes.Buffer
	b.WriteString("// Code generated by internal/contract/internal/gen from contracts/templates; DO NOT EDIT.\n\n")
	b.WriteString("package contract\n\n")
	b.WriteString("// sourceFiles are the project's Aiken sources by path.\n")
	b.WriteString("var sourceFiles = map[string]string{\n")
	for _, p := range paths {
		fmt.Fprintf(&b, "%q: %q,\n", p, files[p])
	}
	b.WriteString("}\n")

	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("contract: format sources: %w", err)
	}
	return out, nil
}

// sourcePaths returns the snapshot's paths in order.
func sourcePaths() []string {
	out := make([]string, 0, len(sourceFiles))
	for p := range sourceFiles {
		out = append(out, p)
	}
	slices.Sort(out)
	return out
}

// SourcesOf returns v's module followed by the project modules it uses,
// directly or through another, in path order. Modules of the standard
// library are not part of the project and are left out.
func SourcesOf(v Validator) []Source {
	seen := map[string]bool{v.Module: true}
	queue := []string{v.Module}
	for len(queue) > 0 {
		p := queue[0]
		queue = queue[1:]
		for _, m := range imports(sourceFiles[p]) {
			lib := "lib/" + m + ".ak"
			if _, ok := sourceFiles[lib]; ok && !seen[lib] {
				seen[lib] = true
				queue = append(queue, lib)
			}
		}
	}

	out := []Source{{Path: v.Module, Text: sourceFiles[v.Module]}}
	for _, p := range sourcePaths() {
		if seen[p] && p != v.Module {
			out = append(out, Source{Path: p, Text: sourceFiles[p]})
		}
	}
	return out
}

// imports lists the modules a source file names in its `use` lines, as
// "continuum/types" for `use continuum/types.{VestingDatum}`.
func imports(src string) []string {
	var out []string
	for _, line := range strings.Split(src, "\n") {
		rest, ok := strings.CutPrefix(line, "use ")
		if !ok {
			continue
		}

		end := strings.IndexAny(rest, "{ \t\r")
		if end >= 0 {
			rest = rest[:end]
		}
		out = append(out, strings.TrimSuffix(rest, "."))
	}
	return out
}
