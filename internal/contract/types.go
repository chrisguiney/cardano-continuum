package contract

import (
	"bytes"
	"fmt"
	"go/format"
	"slices"
	"strings"
	"unicode"
)

// typePrefix selects the blueprint definitions RenderTypes writes Go types
// for: the project's own (contracts/templates/lib/continuum), not the
// stdlib's or the compiler's builtins.
const typePrefix = "continuum/"

// Definition is one CIP-57 schema definition: a primitive (DataType set)
// or a sum of constructors (AnyOf).
type Definition struct {
	// Title is the type's name in its Aiken module.
	Title string `json:"title"`
	// Description is the type's doc comment.
	Description string `json:"description"`
	// DataType is "integer" or "bytes" for a primitive, empty for a sum.
	DataType string `json:"dataType"`
	// AnyOf are a sum type's constructors, in index order.
	AnyOf []Constructor `json:"anyOf"`
}

// Constructor is one constructor of a sum type.
type Constructor struct {
	// Title is the constructor's name.
	Title string `json:"title"`
	// Index is the constructor's tag in its Constr encoding.
	Index int `json:"index"`
	// Fields are the constructor's fields, in encoding order.
	Fields []Field `json:"fields"`
}

// Field is one named field of a constructor.
type Field struct {
	// Title is the field's name in the source.
	Title string `json:"title"`
	// Ref is "#/definitions/<type>", with '/' escaped as "~1".
	Ref string `json:"$ref"`
}

// typeName is the definition f references.
func (f Field) typeName() string { return Schema{Ref: f.Ref}.TypeName() }

// RenderTypes writes the Go source of types_gen.go for bp, read from the
// file named source: one Go type per project definition, with Data to
// encode it as the validator reads it and Parse<Type> to decode it. Two
// shapes are supported, which is all the templates use:
//
//   - a record, one constructor at index 0 whose fields are integers,
//     byte strings or other records: a struct;
//   - an enum, constructors without fields at indices 0..n-1: a uint8
//     whose constants are the constructors' names.
//
// Integers decode only when they fit an int64. Any other shape is an
// error, so a template type the generator cannot express fails make
// contracts instead of being skipped.
func RenderTypes(bp Blueprint, source string) ([]byte, error) {
	names := make([]string, 0, len(bp.Definitions))
	for n := range bp.Definitions {
		if strings.HasPrefix(n, typePrefix) {
			names = append(names, n)
		}
	}
	slices.Sort(names)

	var b bytes.Buffer
	consts := map[string]string{}
	for _, n := range names {
		d := bp.Definitions[n]
		var err error
		switch {
		case isEnum(d):
			err = writeEnum(&b, n, d, consts)
		case len(d.AnyOf) == 1 && d.AnyOf[0].Index == 0:
			err = writeRecord(&b, bp, n, d)
		default:
			err = fmt.Errorf("contract: %s is neither a record nor an enum", n)
		}

		if err != nil {
			return nil, err
		}
	}

	var head bytes.Buffer
	fmt.Fprintf(&head, "// Code generated by internal/contract/internal/gen from %s; DO NOT EDIT.\n\npackage contract\n\nimport (\n", source)
	for _, pkg := range []string{"bytes", "math/big", "strconv"} {
		if strings.Contains(b.String(), pkg[strings.LastIndex(pkg, "/")+1:]+".") {
			fmt.Fprintf(&head, "%q\n", pkg)
		}
	}
	head.WriteString("\n\"github.com/blinklabs-io/plutigo/data\"\n)\n\n")

	out, err := format.Source(append(head.Bytes(), b.Bytes()...))
	if err != nil {
		return nil, fmt.Errorf("contract: format types: %w", err)
	}
	return out, nil
}

// isEnum reports a sum of at least two constructors without fields, at
// indices 0..n-1.
func isEnum(d Definition) bool {
	if len(d.AnyOf) < 2 {
		return false
	}

	for i, c := range d.AnyOf {
		if c.Index != i || len(c.Fields) != 0 {
			return false
		}
	}
	return true
}

func writeEnum(b *bytes.Buffer, name string, d Definition, consts map[string]string) error {
	t := goName(d.Title)
	fmt.Fprintf(b, "// %s is the blueprint type %s.%s\ntype %s uint8\n\n", t, name, docOf(d), t)
	fmt.Fprintf(b, "// The %s constructors, in index order.\nconst (\n", t)

	for i, c := range d.AnyOf {
		k := goName(c.Title)
		if other, ok := consts[k]; ok {
			return fmt.Errorf("contract: constructor %s of %s is also one of %s", k, name, other)
		}
		consts[k] = name

		fmt.Fprintf(b, "// %s is constructor %d of %s.\n", k, i, t)
		if i == 0 {
			fmt.Fprintf(b, "%s %s = iota\n", k, t)
			continue
		}
		fmt.Fprintf(b, "%s\n", k)
	}
	b.WriteString(")\n\n")

	fmt.Fprintf(b, "// Data encodes v as the validator reads it: Constr <index> with no fields.\nfunc (v %s) Data() data.PlutusData { return data.NewConstr(uint64(v)) }\n\n", t)
	fmt.Fprintf(b, "// String names the constructor in snake case.\nfunc (v %s) String() string {\nswitch v {\n", t)

	for _, c := range d.AnyOf {
		fmt.Fprintf(b, "case %s:\nreturn %q\n", goName(c.Title), snake(c.Title))
	}
	fmt.Fprintf(b, "}\nreturn \"%s(\" + strconv.Itoa(int(v)) + \")\"\n}\n\n", t)

	fmt.Fprintf(b, "// Parse%s decodes the validator's encoding of %s.\nfunc Parse%s(d data.PlutusData) (%s, bool) {\n", t, t, t, t)
	fmt.Fprintf(b, "tag, ok := enumTag(d, %d)\nreturn %s(tag), ok\n}\n\n", len(d.AnyOf), t)
	return nil
}

// fieldKind is how a record field is encoded.
type fieldKind struct {
	// goType is the Go type of the field.
	goType string
	// encode is the expression encoding the field named by %s.
	encode string
	// parse is the function decoding one field.
	parse string
}

func resolve(bp Blueprint, ref string) (fieldKind, error) {
	d, ok := bp.Definitions[ref]
	if !ok {
		return fieldKind{}, fmt.Errorf("contract: no definition %s", ref)
	}

	switch {
	case d.DataType == "integer":
		return fieldKind{goType: "int64", encode: "data.NewInteger(big.NewInt(%s))", parse: "intField"}, nil
	case d.DataType == "bytes":
		return fieldKind{goType: "[]byte", encode: "data.NewByteString(bytes.Clone(%s))", parse: "bytesField"}, nil
	case strings.HasPrefix(ref, typePrefix) && d.DataType == "":
		t := goName(d.Title)
		return fieldKind{goType: t, encode: "%s.Data()", parse: "Parse" + t}, nil
	}
	return fieldKind{}, fmt.Errorf("contract: field type %s is not an integer, byte string or project type", ref)
}

func writeRecord(b *bytes.Buffer, bp Blueprint, name string, d Definition) error {
	t := goName(d.Title)
	fs := d.AnyOf[0].Fields
	kinds := make([]fieldKind, len(fs))
	for i, f := range fs {
		k, err := resolve(bp, f.typeName())
		if err != nil {
			return fmt.Errorf("%s.%s: %w", name, f.Title, err)
		}
		kinds[i] = k
	}

	fmt.Fprintf(b, "// %s is the blueprint type %s.%s\ntype %s struct {\n", t, name, docOf(d), t)
	for i, f := range fs {
		fmt.Fprintf(b, "// %s is the %s field (%s).\n%s %s\n", goName(f.Title), f.Title, f.typeName(), goName(f.Title), kinds[i].goType)
	}
	b.WriteString("}\n\n")

	fmt.Fprintf(b, "// Data encodes v as the validator reads it: Constr 0 with its fields in order.\nfunc (v %s) Data() data.PlutusData {\nreturn data.NewConstr(0,\n", t)
	for i, f := range fs {
		fmt.Fprintf(b, kinds[i].encode+",\n", "v."+goName(f.Title))
	}
	b.WriteString(")\n}\n\n")

	fmt.Fprintf(b, "// Parse%s decodes the validator's encoding of %s.\nfunc Parse%s(d data.PlutusData) (%s, bool) {\n", t, t, t, t)
	fmt.Fprintf(b, "fs, ok := record(d, %d)\nif !ok {\nreturn %s{}, false\n}\n\n", len(fs), t)
	for i := range fs {
		fmt.Fprintf(b, "f%d, ok := %s(fs[%d])\nif !ok {\nreturn %s{}, false\n}\n\n", i, kinds[i].parse, i, t)
	}

	fmt.Fprintf(b, "return %s{\n", t)
	for i, f := range fs {
		fmt.Fprintf(b, "%s: f%d,\n", goName(f.Title), i)
	}
	b.WriteString("}, true\n}\n\n")
	return nil
}

// docOf is a definition's description as a doc comment paragraph, empty
// without one.
func docOf(d Definition) string {
	s := strings.TrimSpace(d.Description)
	if s == "" {
		return ""
	}
	return "\n//\n// " + strings.ReplaceAll(s, "\n", "\n// ")
}

// goName turns a snake_case or CamelCase source name into an exported Go
// name: lock_until becomes LockUntil.
func goName(s string) string {
	var b strings.Builder
	up := true
	for _, r := range s {
		if r == '_' {
			up = true
			continue
		}

		if up {
			r = unicode.ToUpper(r)
			up = false
		}
		b.WriteRune(r)
	}
	return b.String()
}

// snake turns a CamelCase constructor name into snake case:
// AddLiquidity becomes add_liquidity.
func snake(s string) string {
	var b strings.Builder
	for i, r := range s {
		if unicode.IsUpper(r) {
			if i > 0 {
				b.WriteByte('_')
			}
			r = unicode.ToLower(r)
		}
		b.WriteRune(r)
	}
	return b.String()
}
