package contract

import (
	"bytes"
	"fmt"
	"go/format"
	"slices"
	"strconv"
	"strings"
)

// Render writes the Go source of registry_gen.go for bp, read from the
// file named source (a repository-relative path, for the header). One
// registry entry per validator: Aiken repeats a validator's code and hash
// in each of its handlers, and the "else" fallback is not a purpose.
func Render(bp Blueprint, source string) ([]byte, error) {
	vs, err := group(bp)
	if err != nil {
		return nil, err
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/contract/internal/gen from %s; DO NOT EDIT.\n\n", source)
	fmt.Fprintf(&b, "package contract\n\n")
	fmt.Fprintf(&b, "// Toolchain is the compiler that wrote the blueprint: %s %s.\n", bp.Preamble.Compiler.Name, bp.Preamble.Compiler.Version)
	fmt.Fprintf(&b, "const Toolchain = %q\n\n", bp.Preamble.Compiler.Name+" "+bp.Preamble.Compiler.Version)
	b.WriteString("var registry = []Validator{\n")

	for _, v := range vs {
		writeEntry(&b, v)
	}

	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("contract: format registry: %w", err)
	}
	return out, nil
}

// draft is one validator gathered from its handlers.
type draft struct {
	// name and module locate the validator's source.
	name, module string
	// purposes are its handlers' purposes, in blueprint order.
	purposes []string
	// code and hash are its compiled code and script hash, in hex.
	code, hash string
	// params, datum and redeemer come from its spend or mint handler.
	params          []string
	datum, redeemer string
}

func group(bp Blueprint) ([]draft, error) {
	var out []draft
	for _, e := range bp.Validators {
		module, name, purpose := e.split()
		module = "validators/" + module + ".ak"
		i := slices.IndexFunc(out, func(d draft) bool { return d.name == name && d.module == module })
		if i < 0 {
			out = append(out, draft{name: name, module: module, code: e.CompiledCode, hash: e.Hash})
			i = len(out) - 1
		}

		d := &out[i]
		if d.code != e.CompiledCode || d.hash != e.Hash {
			return nil, fmt.Errorf("contract: %s: handlers of one validator differ in code", e.Title)
		}

		if purpose == "else" {
			continue
		}
		d.purposes = append(d.purposes, purpose)
		d.params = d.params[:0]
		for _, p := range e.Parameters {
			d.params = append(d.params, p.Title)
		}

		if e.Datum != nil && e.Datum.Schema.TypeName() != "Data" {
			d.datum = e.Datum.Schema.TypeName()
		}

		if e.Redeemer != nil && e.Redeemer.Schema.TypeName() != "Data" {
			d.redeemer = e.Redeemer.Schema.TypeName()
		}
	}

	for _, d := range out {
		if len(d.purposes) == 0 {
			return nil, fmt.Errorf("contract: validator %s has only a fallback handler", d.name)
		}
	}
	slices.SortFunc(out, func(a, b draft) int { return strings.Compare(a.name, b.name) })
	return out, nil
}

func writeEntry(b *bytes.Buffer, d draft) {
	ps := make([]string, len(d.purposes))
	for i, p := range d.purposes {
		ps[i] = strconv.Quote(p)
	}

	b.WriteString("{\n")
	fmt.Fprintf(b, "Name: %q,\n", d.name)
	fmt.Fprintf(b, "Module: %q,\n", d.module)
	fmt.Fprintf(b, "Purposes: []Purpose{%s},\n", strings.Join(ps, ", "))
	b.WriteString("Language: 3,\n")
	fmt.Fprintf(b, "Hash: mustHash(%q),\n", d.hash)
	fmt.Fprintf(b, "Code: mustHex(%q),\n", d.code)
	if len(d.params) > 0 {
		qs := make([]string, len(d.params))
		for i, p := range d.params {
			qs[i] = strconv.Quote(p)
		}
		fmt.Fprintf(b, "Params: []string{%s},\n", strings.Join(qs, ", "))
	}

	if d.datum != "" {
		fmt.Fprintf(b, "Datum: %q,\n", d.datum)
	}

	if d.redeemer != "" {
		fmt.Fprintf(b, "Redeemer: %q,\n", d.redeemer)
	}
	b.WriteString("},\n")
}
